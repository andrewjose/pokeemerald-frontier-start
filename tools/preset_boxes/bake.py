#!/usr/bin/env python3
# Bakes the Frontier Start preset PC boxes into src/data/preset_boxes.h (v1.38).
#
# Input: a raw dump of gPokemonStoragePtr's PokemonStorage (at least 4 + 14*30*80
# + 14*9 bytes) and of the first 16 bytes of gSaveBlock2, both taken right after
# GivePresetPartyAndFillBoxes ran with PRESET_BOXES_BAKED set to FALSE.
#
#   python3 tools/preset_boxes/bake.py storage.bin saveblock2.bin > src/data/preset_boxes.h
import struct, sys

NUM_BOXES = 14          # preset boxes 0-13
SLOTS = 30
MON_SIZE = 80           # struct BoxPokemon
NAME_SIZE = 9           # BOX_NAME_LENGTH + 1

storage = open(sys.argv[1], 'rb').read()
sb2 = open(sys.argv[2], 'rb').read()
ot_id = struct.unpack('<I', sb2[0x0A:0x0E])[0]

out = []
out.append('// Generated by tools/preset_boxes/bake.py: do not edit by hand.')
out.append('// The preset PC boxes as GivePresetPartyAndFillBoxes builds them, made with')
out.append('// OT ID 0x%08X. LoadBakedBoxes re-keys each one to the player.' % ot_id)
out.append('')
out.append('#define BAKED_OT_ID 0x%08X' % ot_id)
out.append('#define BAKED_BOX_COUNT %d' % NUM_BOXES)
out.append('')
names_off = 4 + 14 * SLOTS * MON_SIZE
out.append('static const u8 sBakedBoxNames[BAKED_BOX_COUNT][BOX_NAME_LENGTH + 1] = {')
for b in range(NUM_BOXES):
    n = storage[names_off + b * NAME_SIZE: names_off + (b + 1) * NAME_SIZE]
    out.append('    {' + ', '.join('0x%02X' % c for c in n) + '},')
out.append('};')
out.append('')

mons, where = [], []
for b in range(NUM_BOXES):
    for s in range(SLOTS):
        off = 4 + (b * SLOTS + s) * MON_SIZE
        raw = storage[off:off + MON_SIZE]
        pid, ot = struct.unpack('<II', raw[:8])
        if pid == 0 and ot == 0:
            continue
        mons.append(struct.unpack('<20I', raw))
        where.append((b, s))

out.append('// Box and slot of each baked Pokemon')
out.append('static const u8 sBakedBoxSlots[][2] = {')
for b, s in where:
    out.append('    {%d, %d},' % (b, s))
out.append('};')
out.append('')
out.append('// The Pokemon themselves, encrypted as stored in the PC (struct BoxPokemon)')
out.append('static const u32 sBakedBoxMons[][20] = {')
for m in mons:
    out.append('    {' + ', '.join('0x%08X' % w for w in m) + '},')
out.append('};')
print('\n'.join(out))
